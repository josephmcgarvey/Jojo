use crate::{ProjectId, SessionId};
use serde::{Deserialize, Serialize};
use ts_rs::TS;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum SessionKind {
    Claude,
    Shell,
}

/// Session state shown as a badge (spec section 7.2). `Running` is used for
/// shell sessions, which have no hook-driven states.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum AgentState {
    Starting,
    Idle,
    Working,
    NeedsYou,
    Done,
    Error,
    Running,
    Exited,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
pub struct ProjectInfo {
    pub id: ProjectId,
    /// Absolute path on the daemon's machine.
    pub path: String,
    pub name: String,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
pub struct SessionInfo {
    pub id: SessionId,
    pub project_id: ProjectId,
    pub kind: SessionKind,
    pub command: String,
    pub args: Vec<String>,
    pub label: String,
    /// Unix time in milliseconds.
    #[ts(type = "number")]
    pub created_at: u64,
    pub state: AgentState,
    /// Unix time in milliseconds.
    #[ts(type = "number")]
    pub state_changed_at: u64,
    pub exit_code: Option<i32>,
    pub claude_session_id: Option<String>,
    /// Shown in the badge tooltip and toast: the pending tool for
    /// `needs_you` ("Needs permission: Bash(git push)") or the error type
    /// for `error`. `None` for every other state.
    #[serde(default)]
    pub state_detail: Option<String>,
    /// True once the label is settled: the user renamed the session, or its
    /// first prompt named it (spec 7.2). A later prompt does not replace it.
    #[serde(default)]
    pub renamed: bool,
    /// True when this daemon still holds a screen for the session, so
    /// `Attach` will succeed. Computed by the daemon for every message that
    /// carries a `SessionInfo`; the value stored in state.json is ignored.
    #[serde(default)]
    pub attachable: bool,
}

/// Every control message. Serialized as JSON with a `type` tag naming the
/// variant, for example `{"type":"ListSessions"}`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
#[serde(tag = "type")]
pub enum ControlMsg {
    Hello { protocol_version: u32, jojod_version: String },

    ListProjects,
    Projects { projects: Vec<ProjectInfo> },
    AddProject { path: String, name: String },
    ProjectAdded { project: ProjectInfo },
    RemoveProject { id: ProjectId },
    ProjectRemoved { id: ProjectId },
    ListDir { path: String },
    DirEntries { path: String, entries: Vec<String> },

    ListSessions,
    Sessions { sessions: Vec<SessionInfo> },
    CreateSession {
        /// Chosen by the client, not generated by the daemon. This lets a
        /// pane match the `SessionCreated`/`SessionExited`/`Error` that
        /// answers its own request even with several creates in flight. A
        /// `session_id` already in use (live or in `state.json`) is
        /// rejected with `Error { request: "CreateSession", session_id:
        /// Some(id), message: "session id already in use" }`.
        session_id: SessionId,
        project_id: ProjectId,
        kind: SessionKind,
        cols: u16,
        rows: u16,
        /// Shell program for `SessionKind::Shell`; `None` uses the daemon default.
        shell: Option<String>,
        /// For `SessionKind::Claude`: a `claude_session_id` to continue. The
        /// daemon runs `claude --resume <id>` (spec 5.4).
        #[serde(default)]
        resume: Option<String>,
    },
    SessionCreated { session: SessionInfo },
    SessionUpdated { session: SessionInfo },
    Attach { session_id: SessionId, cols: u16, rows: u16 },
    Detach { session_id: SessionId },
    Resize { session_id: SessionId, cols: u16, rows: u16 },
    Kill { session_id: SessionId },
    CloseSession { session_id: SessionId },
    SessionRemoved { session_id: SessionId },
    RenameSession { session_id: SessionId, label: String },
    SessionExited { session_id: SessionId, exit_code: Option<i32> },
    /// The user has seen this session's pane: a `done` session becomes
    /// `idle` (spec 7.3 rule 2). App to daemon.
    MarkSeen { session_id: SessionId },
    /// One Claude Code hook payload, as raw JSON, from `jojod hook` (spec
    /// 7.1). Hook relay to daemon; the daemon sends no reply.
    HookEvent { session_id: SessionId, payload: String },

    Shutdown,
    /// Reports a failure, either in response to a specific request or for a
    /// condition detected outside of handling one.
    Error {
        /// Almost always the `type` tag of the message that caused the error
        /// (for example `"Resize"`). Four values instead name a condition
        /// detected outside of handling one particular request:
        /// - `"Output"`: this client fell behind on a session's output and was
        ///   detached from it; attach again for a fresh snapshot.
        /// - `"Events"`: this client missed broadcast events (its subscription
        ///   lagged); the connection is closing, so reconnect and list again.
        /// - `"Frame"`: a frame this client sent could not be decoded (malformed
        ///   JSON, unknown frame type, or a data frame shorter than its 16-byte
        ///   session id).
        /// - `"Hello"`: the client's `protocol_version` did not exactly match
        ///   the daemon's; the connection is closing.
        request: String,
        message: String,
        /// The session the error concerns, when there is one (for example
        /// a `CreateSession` whose program failed to start).
        #[serde(default)]
        session_id: Option<SessionId>,
    },
}
